/*-------------------------------------------------------
    return scratch size of cqrnfHousholderxxx
    Input:
    M,L  matrix size
-------------------------------------------------------*/
size_t cqrnfHousholder_getScratchSize(int M, int L)
{
    (void)M,(void)L;
    return 4 * ((L*sizeof(float32_t) + (2 * BBE_SIMD_WIDTH - 1))&(~(2 * BBE_SIMD_WIDTH - 1)));
}
