/*-----------------------------------------------------------
  return scratch size for qrfsHousholderxxx
  Input:
  M,N,L  matrix sizes
-----------------------------------------------------------*/
size_t qrfsHousholder_getScratchSize(int M, int N, int L)
{
    (void)M,(void)N,(void)L;
    NASSERT(L>0 && L%(BBE_SIMD_WIDTH/2)==0);
    return 2*L*sizeof(float32_t);
}
